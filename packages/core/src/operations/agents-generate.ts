import { join } from 'node:path';
import { loadConfig } from '../config-loader.js';
import type { EngineContext } from '../engine-context.js';
import { QaError } from '../errors.js';
import { GENERATED_SUBAGENT_MARKER, SUBAGENT_DIRECTORY, renderSpokeSubagents } from '../spoke-subagents.js';

export interface AgentsGenerateResult {
  readonly directory: string;
  readonly subagents: readonly {
    readonly spokeId: string;
    readonly path: string;
    readonly model: string;
  }[];
}

/**
 * `qa agents generate` (P4-03): writes one Claude Code subagent per spoke into the project's
 * `.claude/agents/`, each carrying the `model:` that `agents.models` routes its spoke to (`inherit`
 * when none is configured). Rewrites only files it generated: a file of the same name without the
 * marker is the operator's own and is refused with `AGENTS_FILE_NOT_GENERATED`, writing nothing.
 */
export async function runAgentsGenerate(context: EngineContext): Promise<AgentsGenerateResult> {
  const { agents } = await loadConfig(context);
  const subagents = renderSpokeSubagents(agents.models);
  const absolute = (path: string): string => join(context.projectRoot, ...path.split('/'));

  for (const subagent of subagents) {
    const target = absolute(subagent.path);
    if (
      (await context.fs.pathExists(target)) &&
      !(await context.fs.readFile(target)).includes(GENERATED_SUBAGENT_MARKER)
    ) {
      throw new QaError(
        'AGENTS_FILE_NOT_GENERATED',
        `"${subagent.path}" exists and was not generated by qa agents generate`,
        { remediation: 'Rename or remove that file, then run qa agents generate again.' },
      );
    }
  }
  await context.fs.mkdir(absolute(SUBAGENT_DIRECTORY));
  for (const subagent of subagents) {
    await context.fs.writeFile(absolute(subagent.path), subagent.content);
  }
  return {
    directory: SUBAGENT_DIRECTORY,
    subagents: subagents.map((subagent) => ({
      spokeId: subagent.spokeId,
      path: subagent.path,
      model: subagent.model ?? 'inherit',
    })),
  };
}
