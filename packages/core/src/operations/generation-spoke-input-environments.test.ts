import { join } from 'node:path';
import { SCHEMA_VERSION, type SelectorElement, type TestCase } from '@qa-ai-stlc/schemas';
import { createFakeFileSystem, type FakeFileSystem } from '@qa-ai-stlc/test-utils/fake-file-system';
import { describe, expect, it } from 'vitest';
import { createFakeEngineContext } from '../test-support/fake-engine-context.js';
import { runBuildGenerationSpokeInput } from './generation-spoke-input.js';

const NOW = new Date('2026-10-19T10:00:00.000Z');
const TEST_CASE: TestCase = {
  schemaVersion: SCHEMA_VERSION,
  id: 'checkout-guest',
  feature: 'checkout',
  requirementIds: ['req-1'],
  testType: 'e2e',
  title: 'A guest can check out',
  steps: [{ description: 'Add an item to the cart' }],
  expectedResult: 'The order confirmation page is shown',
  status: 'approved',
  createdAt: '2026-10-18T09:00:00.000Z',
};

const MODULE_SOURCE = [
  '// Generated by @qa-ai-stlc/explorer@1.3.0 from the selector registry',
  'export const GENERATOR_VERSION = "1.3.0";',
  '',
  '// elements: local-button',
  'export function localButton(page: Page): Locator {',
  '  return page.getByTestId("local-button");',
  '}',
  '',
  '// elements: public-button',
  'export function publicButton(page: Page): Locator {',
  '  return page.getByTestId("public-button");',
  '}',
  '',
].join('\n');

const CONFIG_YAML = `${[
  'schemaVersion: 1',
  'testing: { e2e: in-scope, api: out-of-scope, a11y: undecided, security: undecided }',
  'environments:',
  '  local: { baseUrl: "http://localhost:4200", allowlist: ["localhost"] }',
  '  public: { baseUrl: "https://shop.example.test", allowlist: ["shop.example.test"] }',
  'identities: {}',
  'data: { strategy: manual, ownerMarker: qa-ai-stlc }',
  'selectors: { policy: playwright-default, testIdAttribute: data-testid }',
  'agents: { parallelism: 1, spokeTimeoutSeconds: 60, retries: 1 }',
].join('\n')}\n`;

function button(elementId: string, name: string, environment: string, pageUrl: string): SelectorElement {
  return {
    elementId,
    name,
    kind: 'button',
    locatorCandidates: [{ strategy: 'testId', value: elementId, fragile: false }],
    stabilityScore: 1,
    lastVerifiedAt: '2026-10-19T09:00:00.000Z',
    source: 'crawl',
    pageUrl,
    environment,
  };
}

async function seedProject(fs: FakeFileSystem, testCase: unknown = TEST_CASE): Promise<void> {
  await fs.mkdir(join('project', '.qa', 'artifacts', 'cases', 'checkout'));
  await fs.writeFile(
    join('project', '.qa', 'artifacts', 'cases', 'checkout', 'checkout-guest.json'),
    JSON.stringify(testCase),
  );
  await fs.writeFile(join('project', '.qa', 'config.yaml'), CONFIG_YAML);
  await fs.mkdir(join('project', '.qa', 'selectors'));
  await fs.writeFile(
    join('project', '.qa', 'selectors', 'registry.json'),
    JSON.stringify({
      schemaVersion: SCHEMA_VERSION,
      generatedAt: '2026-10-19T09:00:00.000Z',
      elements: [
        button('local-button', 'localButton', 'local', 'http://localhost:4200/'),
        button('public-button', 'publicButton', 'public', 'https://shop.example.test/'),
      ],
    }),
  );
  await fs.mkdir(join('project', 'tests', 'qa'));
  await fs.writeFile(join('project', 'tests', 'qa', 'locators.ts'), MODULE_SOURCE);
}

function contextOf(fs: FakeFileSystem) {
  return createFakeEngineContext({ fs, clock: { now: () => NOW } });
}

// The registry holds every environment of the project; a spec is written for one (ADR-0020).
describe('runBuildGenerationSpokeInput with several environments', () => {
  it('offers the spoke only the elements of the environment the spec is for', async () => {
    const fs = createFakeFileSystem();
    await seedProject(fs);

    const input = await runBuildGenerationSpokeInput(contextOf(fs), {
      testCaseId: TEST_CASE.id,
      elementIds: ['local-button'],
      environment: 'local',
    });

    expect(input.registrySlice?.elements.map((entry) => entry.elementId)).toEqual(['local-button']);
    expect(input.locatorModule?.exports).toEqual([{ elementId: 'local-button', name: 'localButton' }]);
  });

  it('refuses an element that only the other environment has', async () => {
    const fs = createFakeFileSystem();
    await seedProject(fs);

    await expect(
      runBuildGenerationSpokeInput(contextOf(fs), {
        testCaseId: TEST_CASE.id,
        elementIds: ['public-button'],
        environment: 'local',
      }),
    ).rejects.toMatchObject({ code: 'core.generation_contract.unknown_element_id' });
  });

  it('does not resolve an expectation against an element of the other environment', async () => {
    const fs = createFakeFileSystem();
    await seedProject(fs, {
      ...TEST_CASE,
      steps: [
        {
          description: 'Add an item to the cart',
          expectations: [{ kind: 'visible', selector: '[data-testid="public-button"]' }],
        },
      ],
    });

    const input = await runBuildGenerationSpokeInput(contextOf(fs), {
      testCaseId: TEST_CASE.id,
      elementIds: [],
      environment: 'local',
    });

    expect(input.unresolvedExpectations).toEqual([
      {
        where: 'step-1',
        kind: 'visible',
        selector: '[data-testid="public-button"]',
        reason: 'selector-not-in-registry',
      },
    ]);
  });

  it('asks which environment when there are several and none is given', async () => {
    const fs = createFakeFileSystem();
    await seedProject(fs);

    await expect(
      runBuildGenerationSpokeInput(contextOf(fs), { testCaseId: TEST_CASE.id, elementIds: ['local-button'] }),
    ).rejects.toMatchObject({ code: 'BROWSER_ENVIRONMENT_AMBIGUOUS' });
  });
});
